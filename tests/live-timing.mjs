import assert from 'node:assert/strict';
import {LiveTimingState} from '../static/live-timing.js';
let now=0;const state=new LiveTimingState(()=>now);
now=100;state.tick();assert.equal(state.snapshot().peakDelay,0);
state.reply({server_time:1000,values:{a:{quality:'good',value:1,timestamp:999.5},b:{quality:'good',timestamp:999},bad:{quality:'bad',timestamp:1}}},'PLC');
now=300;state.tick();let sample=state.snapshot();assert.equal(sample.replyAge,200);assert.equal(sample.dataAge,1200);assert.equal(sample.source,'PLC');
now=2300;state.tick();assert.equal(state.snapshot().peakDelay,1900);assert.equal(state.snapshot().replyAge,2200);
state.reply({server_time:1003,values:{a:{quality:'good',timestamp:1003}}},'PLC');assert.equal(state.snapshot().dataAge,0);assert.equal(state.snapshot().count,2);assert.equal(state.snapshot().peakDelay,1900);
now=10000;state.resume();now+=100;state.tick();assert.equal(state.snapshot().peakDelay,1900);
state.reset();assert.equal(state.snapshot().replyAge,null);assert.equal(state.snapshot().count,0);
state.reply({values:{}},'Empty');assert.equal(state.snapshot().dataAge,null);
console.log('Live timing: browser stalls retained, server-reply and feedback ages separated, hidden-tab time excluded.');
