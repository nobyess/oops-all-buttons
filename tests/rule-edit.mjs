import assert from 'node:assert/strict';
import {moveRule,duplicateRule} from '../static/rule-edit.js';
const items=[{id:'a',operand:{value:1},contentRefs:{path:'tag'}},{id:'b'},{id:'c'}];
assert.equal(moveRule(items,'a',-1),false);
assert.equal(moveRule(items,'a',1),true);assert.deepEqual(items.map(item=>item.id),['b','a','c']);
assert.equal(moveRule(items,'a',-1),true);
assert.equal(moveRule(items,'missing',1),false);
const copy=duplicateRule(items,'a');assert.notEqual(copy.id,'a');assert.equal(items[1],copy);
copy.operand.value=9;copy.contentRefs.path='other';assert.equal(items[0].operand.value,1);assert.equal(items[0].contentRefs.path,'tag');
assert.equal(duplicateRule(items,'missing'),null);
console.log('Event order boundaries, fresh duplicate IDs, and independent nested settings passed.');
