import assert from 'node:assert/strict';
import {explorerViewport} from '../static/explorer-drag.js';
const wrapper={clientLeft:0,clientWidth:210,getBoundingClientRect:()=>({left:14,top:300,bottom:900})};
const list={clientLeft:1,clientWidth:600,closest:()=>wrapper,getBoundingClientRect:()=>({left:14,top:300,bottom:880})};
assert.deepEqual(explorerViewport(list),{left:15,right:224,top:300,bottom:880,width:209});
list.getBoundingClientRect=()=>({left:-100,top:300,bottom:880});
assert.equal(explorerViewport(list).left,14,'Horizontal scrolling cannot push the marker outside its viewport');
assert.equal(explorerViewport(list).right,224);
wrapper.clientWidth=160;
assert.equal(explorerViewport(list).width,160,'Resizing the sidebar updates the marker width');
console.log('Explorer drop indicator stays inside the visible list viewport');
