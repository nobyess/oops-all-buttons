import assert from 'node:assert/strict';
import {clipboardImage,imageFileData,installClipboardImagePaste} from '../static/clipboard-image.js';
const image={type:'image/png',size:100,name:'image.png'},text={type:'text/plain'};
const event={target:{closest:()=>false},clipboardData:{items:[{kind:'string',type:'text/plain'},{kind:'file',type:'image/png',getAsFile:()=>image}]},preventDefault(){this.prevented=true;}};
assert.equal(clipboardImage(event),image);
assert.equal(clipboardImage({...event,target:{closest:()=>true}}),null);
assert.equal(clipboardImage({...event,clipboardData:{files:[text,image]}}),image);
assert.equal(clipboardImage({...event,clipboardData:{files:[text]}}),null);
let listener,allowed=true,pasted=[],errors=[];
installClipboardImagePaste({addEventListener:(type,fn)=>{assert.equal(type,'paste');listener=fn;}},{canPaste:()=>allowed,onPaste:async file=>pasted.push(file),onError:error=>errors.push(error)});
listener(event);await new Promise(resolve=>setImmediate(resolve));assert(event.prevented);assert.deepEqual(pasted,[image]);
allowed=false;listener(event);await new Promise(resolve=>setImmediate(resolve));assert.equal(pasted.length,1);
await assert.rejects(imageFileData({size:6*1024*1024}),/5 MB/);
globalThis.FileReader=class {readAsDataURL(){this.result='data:image/png;base64,abc';this.onload();}};
assert.equal(await imageFileData(image),'abc');
console.log('Clipboard images, text-field exclusions, editor gating, file limits, and image upload encoding passed.');
