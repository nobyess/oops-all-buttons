import assert from 'node:assert/strict';
import {firstSelection,newRule} from '../static/selection-defaults.js';
assert.equal(firstSelection([['a','First'],['b','Second']],undefined),'a');
assert.equal(firstSelection([['a','First'],['b','Second']],null),'a');
assert.equal(firstSelection([['a','First'],['b','Second']],'missing'),'a');
assert.equal(firstSelection([['a','First'],['b','Second']],'b'),'b');
assert.equal(firstSelection([['','Select a tag…'],['a','First']],undefined),'');
assert.equal(firstSelection([],undefined),'');
const base={id:'new',actions:{toggle:{},set:{},increment:{}},visualActions:{show:'Show',hide:'Hide'}};
assert.deepEqual(newRule(base),{id:'new',tag:'',trigger:'mouse_down',action:'toggle',value:1});
assert.equal(newRule({...base,isPage:true}).trigger,'page_open');
assert.equal(newRule({...base,isListbox:true}).trigger,'user_changed');
const event=newRule({...base,isEvent:true});assert.equal(event.operator,'=');assert.equal(event.action,'show');assert.equal(event.operand.kind,'value');
assert.equal(newRule({...base,isEvent:true,isPage:true,visualActions:{close_popup:'Close',set_colors:'Colors'}}).action,'close_popup');
console.log('New dropdowns and rules select their first valid option; existing choices and placeholder options are retained.');
